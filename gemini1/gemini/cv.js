async function parseApiResponse(response) {
    try {
        console.log("Json response")
        return await response.json();
    } catch {
        console.log("Plain text response")
        return await response.text(); // <--- ALWAYS FALLS BACK TO TEXT
    }
}

// Normalize CV responses
function normalizeCvResponse(data) {
    if (!data) return "No CV generated.";

    let cvText = "";
    // Handle different data types and structures
    if (typeof data === "string") {
        // 1. Look for the raw CV text which is clearly marked in the server log text
        const rawCvMatch = data.match(/\*\*Name:\*\*(.*?)\*\*Education:\*\*\n\*\*-/s);
        if (rawCvMatch && rawCvMatch[0]) {
            cvText = rawCvMatch[0]; // Capture the whole block
        } 
        // 2. Fallback to the original rawResponse extraction from a stringified error object
        else {
            const rawResponseMatch = data.match(/"rawResponse":"(.*?)"/);
            if (rawResponseMatch && rawResponseMatch[1]) {
                cvText = rawResponseMatch[1];
            } else {
                cvText = data; // Use the entire string as a last resort
            }
        }
    } else if (typeof data === "object") {
        cvText = data.response?.cv || data.cvText || data.candidates?.[0]?.content?.parts?.[0]?.text;

        if (!cvText && data.rawResponse) {
            try {
                const parsedRaw = JSON.parse(data.rawResponse);
                cvText = parsedRaw.candidates?.[0]?.content?.parts?.[0]?.text || data.rawResponse;
            } catch {
                cvText = data.rawResponse;
            }
        }
    }

    if (!cvText) {
        return "Could not extract CV content from the response.";
    }

    //  Clean CV text
    let cleanedText = cvText
        .replace(/\*\*/g, '')
        .split('Explanation and Customization Notes:')[0];

    if (cleanedText.includes('Raw response:')) {
        cleanedText = cleanedText.split('Raw response:')[1];
    }
    
    if (cleanedText.includes('\\n')) {
        cleanedText = cleanedText.replace(/\\n/g, '\n');
    }

    cleanedText = cleanedText
        .replace(/\s(\n\n\s*)/g, '\n\n') // Normalize multiple blank lines to exactly one
        .replace(/(\S)\n(\S)/g, '$1 $2') // Combine single-line breaks without separating bullet points (a common issue)
        .replace(/([^\n])\n- /g, '$1\n- ') // Ensure a clean line break before a list item
        .replace(/([^\n])\s?-\s/g, '$1\n- ') // Ensure a clean line break before a list item (handles cases with spaces)
        .trim();

    return cleanedText;
}
// function for the "Improve an Existing CV" mode
function normalizeImprovedCvResponse(data) {
    let cvText = normalizeCvResponse(data); 
    let cleanedText = cvText
        // Replace the " --- " marker with two newlines for clean section breaks
        .replace(/\s*---\s*/g, '\n\n') 
        // Replace all major section headers (like 'Summary:', 'Education:') with two newlines before them
        .replace(/(Summary|Core Skills|Relevant Experience|Work Experience|Education|Languages|SEMINARS|PROJECTS|AWARDS):/g, '\n\n$1:')
        // Replace existing bullet point separators if they are on the same line, inserting a newline before each
        .replace(/- /g, '\n- ') 
        // Clean up any double/triple newlines resulting from the above
        .replace(/\n\s*\n/g, '\n\n')
        .replace(/\*\*/g, '') // Ensure all bolding is stripped before parsing for consistent header detection
        .trim();
        
    return cleanedText;
}
