//  normalize plain text responses for advice
function normalizeTextResponse(data) {
    if (!data) return "No content.";

    let cleanedText = data;
    if (typeof data === "string") {
        const rawResponseMatch = data.match(/"rawResponse":"(.*?)"/);
        if (rawResponseMatch && rawResponseMatch[1]) {
            cleanedText = rawResponseMatch[1];
        }
    }

    if (typeof data === 'object' && data.rawResponse) {
      cleanedText = data.rawResponse;
    }

    cleanedText = cleanedText
        .replace(/\\n/g, '\n')
        .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
        .replace(/\n\n/g, '</p><p>')
        .replace(/\n/g, '<br>');

    return `<p>${cleanedText}</p>`;
}

