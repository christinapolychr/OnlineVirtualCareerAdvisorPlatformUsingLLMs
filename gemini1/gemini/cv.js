//  CAREER ADVICE 
async function fetchCareerAdvice(selectedCareer) {
    const adviceOutput = document.getElementById("careerAdviceOutput");
    adviceOutput.innerHTML = `<p class="text-center font-semibold text-gray-600 dark:text-gray-400">Fetching career advice for 
    ${selectedCareer}...</p>`;
//advice prompt
    const prompt = `Provide 3-5 career advice points for a ${selectedCareer}. Rerutn each as a bullet point.
    Return the output as a JSON object with this exact structure: { "advice": 
    ["Point 1", "Point 2", "Point 3", "Point 4", "Point 5"] }.
    Just return valid JSON.`;

    try {
        const response = await fetch("http://localhost:3000/generate", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ prompt }),
        });

        const data = await parseApiResponse(response);

        let formattedAdvice;

        if (!response.ok) {
            //adviceOutput.innerHTML = `<p class="text-red-500 text-center">${formattedAdvice}</p>`;
            let errorMessage = data.rawResponse || data.error || "An unknown error occurred.";
            
            // Normalize the error message if it's the raw text
            const formattedError = normalizeTextResponse(errorMessage);
            adviceOutput.innerHTML = `<p class="text-red-500 text-center">${formattedError}</p>`;
            return;
        }
        const adviceArray = data.response?.advice; // Safely access the array from the JSON object
        if (Array.isArray(adviceArray) && adviceArray.length > 0) {
            // Build an HTML unordered list (<ul>) from the array
            formattedAdvice = `<ul>`;
            adviceArray.forEach(point => {
                // Apply simple text normalization to each point (like bolding)
                let cleanedPoint = point
                    .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
                    .replace(/\\n/g, ''); // Remove any escaped newlines

                formattedAdvice += `<li class="mb-2 ml-4 list-disc text-gray-700 dark:text-gray-300">${cleanedPoint}</li>`;
            });
            formattedAdvice += `</ul>`;
            
        } else {
            // Fallback if the advice array is missing or empty
            formattedAdvice = `<p>Successfully received a response, but the advice list was empty or malformed.</p>`;
        }
        
        // Use the new HTML list for display
        adviceOutput.innerHTML = `
            <h3 class="text-xl font-bold text-gray-900 dark:text-gray-100">Career Advice</h3>
            <div>${formattedAdvice}</div>
        `;

    } catch (err) {
        console.error("Error fetching career advice:", err);
        adviceOutput.innerHTML = `<p class="text-red-500 text-center">Error: ${err.message}</p>`;
    }
}
